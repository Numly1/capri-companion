function clean(value, limit = 140) {
  return typeof value === 'string' ? value.replace(/[\u0000-\u001f\u007f]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, limit) : '';
}
function word(character) { return !!character && /[\p{L}\p{N}_]/u.test(character); }
function has(text, terms) {
  return terms.some(term => {
    const japanese = /[\u3040-\u30ff\u3400-\u9fff]/u.test(term);
    let start = 0, at;
    while ((at = text.indexOf(term, start)) !== -1) {
      const end = at + term.length;
      if (japanese || (!word(text[at - 1]) && !word(text[end]))) return true;
      start = end;
    }
    return false;
  });
}
function choose(id, language, lines) {
  const key = `${language}:${id}`;
  let index = Math.floor(Math.random() * lines.length);
  if (lines.length > 1 && index === previous.get(key)) index = (index + 1) % lines.length;
  previous.set(key, index);
  return lines[index];
}

/**
 * Return a finite local RU/JP reply. No actions or network requests are performed.
 * cfg: { voiceLanguage?: 'ru'|'ja', lang?: string, userName?: string }
 * context?: { enabled?: boolean, available?: boolean, drawing?: {app: string},
 *   music?: { title?: string, artist?: string, playing?: boolean }, now?: Date }
 * Older activity/track metadata is also accepted. Disabled/unavailable context is never used.
 * `now` is optional for deterministic tests; normal operation uses the machine's local clock/timezone.
 */
function reply(text, cfg = {}, context = {}) {
  cfg = cfg && typeof cfg === 'object' ? cfg : {};
  context = context && typeof context === 'object' ? context : {};
  const selectedLanguage = cfg.responseLanguage || cfg.lang || 'ru';
  const ja = typeof selectedLanguage === 'string' && /^ja(?:-|$)/i.test(selectedLanguage);
  const language = ja ? 'ja' : 'ru';
  const name = clean(cfg.userName, 80);
  const contextAvailable = context.enabled !== false && context.available !== false;
  const track = contextAvailable ? (context.music || context.track) : null;
  const activity = contextAvailable ? (context.activity || (context.drawing ? 'drawing' : (track && track.playing !== false ? 'music' : null))) : null;
  if (typeof text === 'string' && text.length > MAX_INPUT) return ja ? 'ちょっと長すぎるよ。8000文字以内で、もう一度お願い。' : 'Такой поток не влезает в мой маленький буфер. Сократи сообщение до 8000 символов.';
  if (typeof text !== 'string' || !text.trim()) return ja ? 'ひとこと送ってみて。「こんにちは」でもいいよ。' : 'Кинь мне хоть пару букв. «Привет» тоже считается.';
  const input = clean(text, MAX_INPUT).toLowerCase().replace(/ё/g, 'е');
  if (has(input, ['как меня зовут', 'мое имя', 'что ты знаешь обо мне', '私の名前'])) {
    return name ? (ja ? `設定では「${name}」だよ。呼び方を変えるなら設定で教えて。` : `В настройках ты — ${name}. Другое обращение можно задать там.`)
      : (ja ? '呼び方はまだ設定されてないよ。設定で名前を教えてね。' : 'Имя пока не задано. Впиши его в настройках — буду обращаться по имени.');
  }
  if (has(input, ['меня зовут', '私の名前は'])) {
    return ja ? 'よろしくね。いつもその名前で呼んでほしいなら、設定の名前欄にも入れてね。' : 'Приятно познакомиться! Чтобы я постоянно так обращалась, впиши имя в настройках.';
  }
  if (has(input, ['что я слушаю', 'что слушаю', 'какую музыку я слушаю', 'что сейчас играет', 'что играет', 'какой трек', 'какая песня играет', '何を聴いてる', '今の曲'])) {
    const title = clean(track && track.title);
    const artist = clean(track && track.artist);
    if (!title) return ja ? '曲名の情報はまだ渡されてないよ。聴こえているふりはしないよ。' : 'Название трека мне не передали. Делать вид, что слышу музыку, не буду.';
    if (track.playing === false) return ja ? `最後に渡された曲は「${title}」${artist ? ` — ${artist}` : ''}。再生状態は停止になってるよ。`
      : `Последний переданный трек — «${title}»${artist ? ` — ${artist}` : ''}. По переданному состоянию воспроизведение остановлено.`;
    return ja ? `渡された曲の情報は「${title}」${artist ? ` — ${artist}` : ''}。音そのものを聴いたわけじゃないよ。` : `По переданным сведениям играет «${title}»${artist ? ` — ${artist}` : ''}. Сам звук я не слушаю.`;
  }
  if (has(input, ['что я рисую', 'видишь рисунок', 'оцени рисунок', '何を描いてる', '絵を見て'])) {
    return activity === 'drawing'
      ? (ja ? 'お絵描き中という状態は届いてるよ。でも絵の内容は見えてない。色や構図を当てたりはしないよ。' : 'Мне передано, что ты рисуешь. Сам рисунок не вижу, поэтому цвета и сюжет не выдумываю.')
      : (ja ? '絵の画像は渡されてないから、今何を描いているかはわからないよ。' : 'Изображение рисунка мне не передали, так что не угадаю, что на нём.');
  }
  if (has(input, ['что я делаю', 'чем я занимаюсь', 'какое приложение', '今何してる', '何をしてる'])) {
    const activities = {
      drawing: ['рисование', 'お絵描き'], music: ['музыка', '音楽'], browser: ['браузер', 'ブラウザー'],
      coding: ['работа с кодом', 'コーディング'], writing: ['работа с текстом', '文章作業'],
      gaming: ['игра', 'ゲーム'], video: ['видео', '動画'], reading: ['чтение', '読書'], meeting: ['встреча', 'ミーティング'],
    };
    const label = typeof activity === 'string' && Object.hasOwn(activities, activity) ? activities[activity] : null;
    return label ? (ja ? `届いている状態は「${label[1]}」。中身までは見てないよ。` : `По переданному состоянию сейчас — ${label[0]}. Содержимое окна я не вижу.`)
      : (ja ? '今の作業状態は渡されてないよ。画面を見て当てることはできないんだ。' : 'Текущий вид занятия мне не передали. Самостоятельно смотреть в окно и угадывать я не умею.');
  }
  const now = context.now instanceof Date && Number.isFinite(context.now.getTime()) ? context.now : new Date();
  if (has(input, ['который час', 'сколько времени', 'текущее время', 'what time', '何時'])) {
    return (ja ? 'このPCの時計では ' : 'По часам этого компьютера — ') + new Intl.DateTimeFormat(ja ? 'ja-JP' : 'ru-RU', { hour: '2-digit', minute: '2-digit' }).format(now) + (ja ? '。' : '.');
  }
  if (has(input, ['какая дата', 'какое сегодня число', 'какой сегодня день', 'сегодняшняя дата', '今日の日付', '今日は何日', '何曜日'])) {
    return (ja ? 'このPCの日付では ' : 'По календарю этого компьютера — ') + new Intl.DateTimeFormat(ja ? 'ja-JP' : 'ru-RU', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' }).format(now) + (ja ? '。' : '.');
  }
  for (const [id, triggers, ru, jp] of INTENTS) {
    if (has(input, triggers)) return choose(id, language, ja ? jp : ru).replace(/\{user\}/g, name ? (ja ? `、${name}` : `, ${name}`) : '');
  }
  return choose('fallback', language, ja ? [
    'その話には、今の決まった返事ではうまく答えられないよ。「冗談」や「何ができる？」を試すか、設定でAIを有効にしてね。',
    'おっと、そのカオスは今の台詞リストの外。オフラインの反応は有限なんだ。挨拶や励ましならできるよ。自由な会話は設定のAIから。',
  ] : [
    'Этот хаос пока за пределами моих готовых реплик. Сейчас я офлайн: попроси шутку, поддержку или спроси «что умеешь». Для свободного ответа включи ИИ в настройках.',
    'Не буду изображать всезнающую нейросеть: здесь у меня конечный набор ответов. Могу пошутить, поддержать, назвать время. Свободный разговор — через ИИ в настройках.',
  ]);
}

